"""
Shared Single-Split Chronological Evaluation Pipeline.

Contract:
1. Purging & Isolation:
   - Chronological partitions:
     a) Model Train: [0, train_end_idx)
     b) Model Validation: [val_start_idx, val_end_idx)
        where val_start_idx = train_end_idx + horizon_bars
     c) Rule Development: [dev_start_idx, dev_end_idx)
        where dev_start_idx = val_end_idx + horizon_bars
     d) Final Out-of-Sample Test: [test_start_idx, n)
        where test_start_idx = dev_end_idx + horizon_bars
   - Under this setup, labels in partition X never overlap or refer to prices in partition X+1.
2. Strategy Selection:
   - NSGA-II evolves chromosomes strictly on the Development partition.
   - The representative strategy is frozen based on Development metrics BEFORE evaluating the Test partition.
   - The test partition is evaluated once on the frozen representative strategy.
   - Exploratory inspection of the full front on test is kept clearly separate.
3. Reproducibility:
   - An explicit integer seed ensures reproducible random numbers, model fitting, and GA populations.
"""
from typing import Dict, List, Optional, Tuple
import numpy as np
import pandas as pd
import random

from src.config import PREDICTION_HORIZON_BARS, BENCHMARK_TICKER
from src.data_loader import fetch_and_cache_ticker
from src.feature_pipeline import prepare_feature_dataset
from src.predictor import MarketPredictor
from src.evolutionary_core import NSGA2Optimizer, Individual
from src.backtest_engine import (
    run_vectorized_simulation_fast,
    get_detailed_simulation_results,
)


def create_purged_splits(
    df: pd.DataFrame,
    horizon_bars: int = PREDICTION_HORIZON_BARS,
    train_frac: float = 0.50,
    val_frac: float = 0.15,
    dev_frac: float = 0.15,
) -> Dict[str, pd.DataFrame]:
    """
    Creates four strictly chronologically ordered partitions with purged gap horizons.
    train -> [purge] -> val -> [purge] -> dev -> [purge] -> test
    """
    n = len(df)
    n_train = int(n * train_frac)
    n_val = int(n * val_frac)
    n_dev = int(n * dev_frac)

    # Train
    train_end = n_train
    train_df = df.iloc[:train_end].copy().reset_index(drop=True)

    # Val (purged by horizon_bars)
    val_start = train_end + horizon_bars
    val_end = val_start + n_val
    if val_end > n:
        raise ValueError("Dataset too small for specified splits and purge horizons.")
    val_df = df.iloc[val_start:val_end].copy().reset_index(drop=True)

    # Dev (for evolutionary strategy search, purged)
    dev_start = val_end + horizon_bars
    dev_end = dev_start + n_dev
    if dev_end > n:
        raise ValueError("Dataset too small for specified splits and purge horizons.")
    dev_df = df.iloc[dev_start:dev_end].copy().reset_index(drop=True)

    # Test (for frozen final evaluation, purged)
    test_start = dev_end + horizon_bars
    if test_start >= n:
        raise ValueError("Dataset too small for test split after purging.")
    test_df = df.iloc[test_start:].copy().reset_index(drop=True)

    return {
        "train": train_df,
        "val": val_df,
        "dev": dev_df,
        "test": test_df,
        "indices": {
            "train": (0, train_end),
            "val": (val_start, val_end),
            "dev": (dev_start, dev_end),
            "test": (test_start, n),
            "horizon_bars": horizon_bars,
        },
    }


def run_experiment_pipeline(
    ticker: str = "SPY",
    pop_size: int = 40,
    num_generations: int = 15,
    seed: int = 42,
    force_refresh: bool = False,
    progress_callback = None,
) -> Dict:
    """
    Runs the complete single-split chronological evaluation experiment.
    Used identically by the CLI and Streamlit app.
    """
    # Set explicit random seeds
    random.seed(seed)
    np.random.seed(seed)

    # 1. Fetch & Prepare Data
    raw_df = fetch_and_cache_ticker(ticker, force_refresh=force_refresh)
    proc_df, feature_cols = prepare_feature_dataset(raw_df, ticker, save_processed=True)

    # 2. Purged Chronological Splits
    splits = create_purged_splits(proc_df)
    train_df = splits["train"]
    val_df = splits["val"]
    dev_df = splits["dev"]
    test_df = splits["test"]

    # 3. Train Model on Train (+ early stopping on Val)
    predictor = MarketPredictor(ticker, feature_cols)
    predictor.train(train_df, val_df)

    # Generate probabilities across partitions
    # Dev probabilities (generated by model trained on Train/Val, never seen during model training)
    p_up_dev = predictor.predict_proba(dev_df)
    # Test probabilities
    p_up_test = predictor.predict_proba(test_df)

    # 4. Evolve Trading Strategies on Dev partition
    open_dev = dev_df["Open"].to_numpy(dtype=np.float64)
    close_dev = dev_df["Close"].to_numpy(dtype=np.float64)
    high_dev = dev_df["High"].to_numpy(dtype=np.float64)
    low_dev = dev_df["Low"].to_numpy(dtype=np.float64)
    atr_dev = dev_df["atr_14"].to_numpy(dtype=np.float64)
    reg_vol_dev = dev_df["regime_high_vol"].to_numpy(dtype=np.int32)

    optimizer = NSGA2Optimizer(
        open_prices=open_dev,
        close=close_dev,
        high=high_dev,
        low=low_dev,
        p_up=p_up_dev,
        atr=atr_dev,
        regime_vol=reg_vol_dev,
        pop_size=pop_size,
        num_generations=num_generations,
        seed=seed,
    )
    pareto_solutions = optimizer.run(progress_callback=progress_callback)

    # 5. Evaluate Development Performance and Select Representative Strategy
    # Using Dev metrics only!
    dev_summary_rows = []
    for idx, sol in enumerate(pareto_solutions):
        sh, mdd, ret, trades, to = run_vectorized_simulation_fast(
            open_dev, close_dev, high_dev, low_dev, p_up_dev, atr_dev, reg_vol_dev,
            sol.genes, apply_penalty=False
        )
        dev_summary_rows.append({
            "id": idx + 1,
            "dev_sharpe": float(sh),
            "dev_mdd": float(mdd),
            "dev_ret": float(ret),
            "dev_trades": int(trades),
            "dev_turnover": float(to),
            "genes": sol.genes,
        })
    dev_summary_df = pd.DataFrame(dev_summary_rows)

    # Strategy Selection Rule on Dev metrics:
    # Pick the strategy with highest Sharpe Ratio among those with trades >= 3 on dev
    valid_dev = dev_summary_df[dev_summary_df["dev_trades"] >= 3]
    if valid_dev.empty:
        selected_dev_strat = dev_summary_df.sort_values("dev_sharpe", ascending=False).iloc[0]
    else:
        selected_dev_strat = valid_dev.sort_values("dev_sharpe", ascending=False).iloc[0]

    frozen_strategy_id = int(selected_dev_strat["id"])
    frozen_genes = selected_dev_strat["genes"]

    # 6. Evaluate Frozen Representative Strategy on Out-of-Sample Test
    open_test = test_df["Open"].to_numpy(dtype=np.float64)
    close_test = test_df["Close"].to_numpy(dtype=np.float64)
    high_test = test_df["High"].to_numpy(dtype=np.float64)
    low_test = test_df["Low"].to_numpy(dtype=np.float64)
    atr_test = test_df["atr_14"].to_numpy(dtype=np.float64)
    reg_vol_test = test_df["regime_high_vol"].to_numpy(dtype=np.int32)

    detailed_test_result = get_detailed_simulation_results(test_df, p_up_test, frozen_genes)

    # Benchmark test performance
    test_benchmark_ret = (close_test[-1] / close_test[0]) - 1.0
    b_peak = np.maximum.accumulate(close_test)
    test_benchmark_mdd = float(np.max((b_peak - close_test) / b_peak))

    # 7. Exploratory Inspection: evaluate full Pareto front on Test
    # (Explicitly marked as exploratory)
    exploratory_test_rows = []
    for idx, sol in enumerate(pareto_solutions):
        sh, mdd, ret, trades, to = run_vectorized_simulation_fast(
            open_test, close_test, high_test, low_test, p_up_test, atr_test, reg_vol_test,
            sol.genes, apply_penalty=False
        )
        exploratory_test_rows.append({
            "id": idx + 1,
            "exploratory_test_sharpe": float(sh),
            "exploratory_test_mdd": float(mdd),
            "exploratory_test_ret": float(ret),
            "exploratory_test_trades": int(trades),
        })
    exploratory_test_df = pd.DataFrame(exploratory_test_rows)

    # Combined summary dataframe
    summary_df = dev_summary_df.merge(exploratory_test_df, on="id")

    return {
        "ticker": ticker,
        "seed": seed,
        "pop_size": pop_size,
        "num_generations": num_generations,
        "feature_cols": feature_cols,
        "splits": splits,
        "predictor": predictor,
        "pareto_solutions": pareto_solutions,
        "dev_summary_df": dev_summary_df,
        "summary_df": summary_df,
        "frozen_strategy_id": frozen_strategy_id,
        "frozen_genes": frozen_genes,
        "detailed_test_result": detailed_test_result,
        "test_benchmark_ret": float(test_benchmark_ret),
        "test_benchmark_mdd": float(test_benchmark_mdd),
    }
